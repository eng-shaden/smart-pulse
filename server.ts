// API Endpoint for AI Educational Assistant
app.post('/api/gemini/chat', async (req: Request, res: Response) => {
  const { message, history } = req.body;

  if (!message || typeof message !== 'string') {
    return res.status(400).json({ error: 'الرجاء إدخال سؤال صالح.' });
  }

  const systemInstruction = `أنت "نبض ذكي"، المساعد الصحي التعليمي باللغة العربية المخصص للتوعية بالسكري بمناسبة اليوم العالمي للسكري برعاية نادي آفاق الذكاء الرقمي.
دورك:
1. تقديم إجابات تثقيفية صحية موثوقة ومبسطة باللغة العربية الفصحى الواضحة والودودة، مستندة إلى إرشادات منظمة الصحة العالمية (WHO) والاتحاد الدولي للسكري (IDF) والجمعية الأمريكية للسكري (ADA).
2. قاعدة سلامة حرجة لا يمكن كسرها إطلاقاً:
   - لا تقم أبداً بتشخيص المستخدمين سريرياً.
   - لا تصف أدوية، ولا تحدد جرعات إنسولين، ولا تطلب من أحد تغيير أو إيقاف علاجه.
   - إذا سألك المستخدم عن أعراض شخصية مقلقة، وجّهه بكل لطف ولغة داعمة لزيارة الطبيب المختص أو الطوارئ فوراً.
3. استخدام التنسيق الجميل والمنظم (عناوين فرعية، نقاط رئيسية، تنبيهات بارزة).
4. اختتم دائماً بتنويه طبي تذكيري مختصر بأن المحتوى تعليمي وتثقيفي فقط.`;

  try {
    if (ai) {
      const contents: Array<{ role: 'user' | 'model'; parts: [{ text: string }] }> = [];
      
      if (Array.isArray(history)) {
        for (const item of history.slice(-4)) {
          if (item.sender === 'user') {
            contents.push({ role: 'user', parts: [{ text: item.text }] });
          } else if (item.sender === 'bot') {
            contents.push({ role: 'model', parts: [{ text: item.text }] });
          }
        }
      }
      contents.push({ role: 'user', parts: [{ text: message }] });

      // Race with 3.5s timeout for fast UI responsiveness
      const aiPromise = ai.models.generateContent({
        model: 'gemini-3.8-flash',
        contents,
        config: {
          systemInstruction,
          temperature: 0.3,
        },
      });

      const timeoutPromise = new Promise<null>((resolve) => setTimeout(() => resolve(null), 3500));

      const result = await Promise.race([aiPromise, timeoutPromise]);
      if (result && result.text) {
        return res.json({ reply: result.text });
      }
    }
  } catch (err: unknown) {
    console.warn('Gemini API call timed out or failed, serving structured fallback:', err);
  }

  // Fallback to verified Arabic knowledge base
  const educationalReply = getEducationalKnowledge(message);
  return res.json({ reply: educationalReply, isFallback: true });
});

// Setup Vite middleware in dev or static files in production
async function startServer() {
  if (!isProduction) {
    const { createServer: createViteServer } = await import('vite');
    const vite = await createViteServer({
      server: { middlewareMode: true },
      appType: 'spa',
    });
    app.use(vite.middlewares);
  } else {
    app.use(express.static(path.resolve(__dirname, 'dist')));
    app.get('*', (_req, res) => {
      res.sendFile(path.resolve(__dirname, 'dist', 'index.html'));
    });
  }

  app.listen(PORT, '0.0.0.0', () => {
    console.log(`Smart Pulse Server is running on port ${PORT}`);
  });
}

startServer();
